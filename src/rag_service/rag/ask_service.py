"""Orchestrates /v1/ask: scoped retrieval -> conservative evidence selection -> grounded
generation -> strict citation validation. Reuses RetrievalService (no duplicated retrieval)."""
from __future__ import annotations

import json
import re

from rag_service.api.errors import ApiError
from rag_service.api.schemas import RetrievalMethod, RetrieveRequest
from rag_service.api.schemas.ask import (AskRequest, AskResponse, EvidenceItem, GenerationInfo, RetrievalSummary,
                                         VideoReference)
from rag_service.rag.evidence import Candidate, select_evidence
from rag_service.rag.prompt import SYSTEM, build_user_prompt, label
from rag_service.rag.providers import DisabledProvider, LLMError, LLMProvider, LLMUnavailable
from rag_service.services.retrieval_service import RetrievalService

NOTICE = ('Answer generated by an LLM from the cited viewer comments only. It reports what viewers said, '
          'not verified facts; claims are not yet checked by NLI. Links are video-level references, '
          'not comment permalinks.')

_LABEL_RE = re.compile(r'\[(E\d+)\]')


class AskService:
    def __init__(self, retrieval: RetrievalService, provider: LLMProvider):
        self.retrieval = retrieval
        self.provider = provider

    def _default_method(self) -> RetrievalMethod:
        if self.retrieval.engine.has_semantic_index():
            return RetrievalMethod.multiview_hybrid
        return RetrievalMethod.multiview_bm25

    def ask(self, req: AskRequest, request_id: str) -> AskResponse:
        # 1. Fail clearly (no retrieval, no fake answer) when generation is not available.
        if isinstance(self.provider, DisabledProvider):
            raise ApiError(503, 'llm_unavailable', self.provider.reason)

        # 2. Scoped retrieval through the existing service (scope validated, filtering before ranking).
        method = req.method or self._default_method()
        retrieved = self.retrieval.retrieve(
            RetrieveRequest(query=req.query, method=method, top_k=req.candidates, scope={'video_id': req.scope.video_id}),
            request_id)
        normalized = (retrieved.normalization.normalized_query if retrieved.normalization
                      else self.retrieval.engine.normalize(req.query).normalized) or None

        # 3. Conservative evidence selection (see rag/evidence.py for the strategy and its limits).
        candidates = [Candidate(r.document_id, r.video_id, r.text, r.video_url, r.rank) for r in retrieved.results]
        sel = select_evidence(req.query, normalized, candidates)
        evidence = [
            EvidenceItem(label=label(i), document_id=c.document_id, video_id=c.video_id, comment_text=c.text,
                         retrieval_rank=c.retrieval_rank, matched_terms=hits,
                         video_reference=VideoReference(url=c.video_url))
            for i, (c, hits) in enumerate(sel.selected, 1)]
        summary = RetrievalSummary(
            method=method, scope=retrieved.scope, normalized_query=normalized, query_content_terms=sel.query_terms,
            candidates_retrieved=len(candidates), candidates_selected=len(evidence),
            candidates_rejected_no_content_match=len(sel.rejected))
        gen = GenerationInfo(provider=self.provider.name, model=self.provider.model, called=False)

        def response(status, answer=None, reason=None, citations=()):
            return AskResponse(request_id=request_id, query=req.query, status=status, answer=answer,
                               insufficient_reason=reason, citations=list(citations), evidence_supplied=evidence,
                               retrieval=summary, generation=gen, notice=NOTICE)

        if not evidence:
            return response('insufficient_evidence', reason='no_content_term_match')

        # 4. Grounded generation over the selected comments only.
        prompt = build_user_prompt(req.query, [(e.label, e.comment_text) for e in evidence])
        gen.called = True
        try:
            raw = self.provider.generate(SYSTEM, prompt)
        except LLMUnavailable as exc:
            raise ApiError(503, 'llm_unavailable', str(exc)) from exc
        except LLMError as exc:
            raise ApiError(502, 'llm_error', str(exc)) from exc

        # 5. Strict validation: any unknown label or uncited answer rejects the whole output.
        status, answer, cited = parse_model_output(raw)
        if status == 'insufficient_evidence':
            return response('insufficient_evidence', reason='model_declined')
        supplied = {e.label: e for e in evidence}
        inline = _LABEL_RE.findall(answer)
        unknown = sorted((set(cited) | set(inline)) - set(supplied))
        if unknown:
            raise ApiError(502, 'llm_unsupported_citation',
                           f'Model cited labels that were not supplied: {", ".join(unknown)}. Answer rejected.')
        used = sorted(set(cited) | set(inline), key=lambda s: int(s[1:]))
        if not used:
            raise ApiError(502, 'llm_unsupported_citation', 'Model answer cites no supplied comment. Answer rejected.')
        return response('answered', answer=answer, citations=[supplied[x] for x in used])


def parse_model_output(raw: str) -> tuple[str, str, list[str]]:
    """Parse the model's JSON. Raises ApiError(502, llm_invalid_output) if it is not the agreed shape."""
    text = raw.strip()
    if text.startswith('```'):
        text = re.sub(r'^```(?:json)?\s*|\s*```$', '', text)
    try:
        data = json.loads(text)
        status = data['status']
        answer = (data.get('answer') or '').strip()
        cites = [str(c).strip().strip('[]') for c in (data.get('citations') or [])]
    except (ValueError, KeyError, TypeError, AttributeError) as exc:
        raise ApiError(502, 'llm_invalid_output', 'Model output was not the expected JSON object.') from exc
    if status not in ('answered', 'insufficient_evidence'):
        raise ApiError(502, 'llm_invalid_output', f'Unexpected model status {status!r}.')
    if status == 'answered' and not answer:
        raise ApiError(502, 'llm_invalid_output', 'Model reported an answer but returned empty text.')
    return status, answer, cites
